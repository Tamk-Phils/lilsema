-- 1. Create the gallery table
CREATE TABLE IF NOT EXISTS public.gallery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'Photography',
  event_name TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.gallery ENABLE ROW LEVEL SECURITY;

-- 3. Allow public read access (for website visitors to view the gallery)
CREATE POLICY "Public Read Access"
  ON public.gallery
  FOR SELECT
  TO public
  USING (true);

-- 4. Allow service_role full access (used by /api/admin/gallery routes)
CREATE POLICY "Admin Service Role Full Access"
  ON public.gallery
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

-- 5. Storage Policies for the "images" bucket
-- (The public "images" bucket has already been created automatically)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Public Access Images Bucket'
  ) THEN
    CREATE POLICY "Public Access Images Bucket"
      ON storage.objects FOR SELECT
      TO public
      USING (bucket_id = 'images');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Admin Upload Images Bucket'
  ) THEN
    CREATE POLICY "Admin Upload Images Bucket"
      ON storage.objects FOR INSERT
      TO service_role
      WITH CHECK (bucket_id = 'images');
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Admin Delete Images Bucket'
  ) THEN
    CREATE POLICY "Admin Delete Images Bucket"
      ON storage.objects FOR DELETE
      TO service_role
      USING (bucket_id = 'images');
  END IF;
END $$;
